use ratatui::style::Color;

/// Syntax + chrome colors for the editor.
///
/// Prefer semantic fields (`accent`, `success`, `panel_*`, `mode_*`, `git_*`)
/// for new UI instead of hard-coded `Color::Rgb` in the TUI.
#[derive(Debug, Clone, Copy)]
pub struct Theme {
    pub name: &'static str,
    #[allow(dead_code)]
    pub bg: Color,
    pub fg: Color,
    pub keyword: Color,
    pub string: Color,
    pub comment: Color,
    pub number: Color,
    pub type_name: Color,
    pub function: Color,
    pub macro_name: Color,
    pub namespace: Color,
    pub parameter: Color,
    pub property: Color,
    pub constant: Color,
    pub operator: Color,
    pub punctuation: Color,
    pub line_no: Color,
    pub editor_bg: Color,
    pub status_bg: Color,
    pub status_fg: Color,
    pub border: Color,
    pub selection_bg: Color,
    pub search_bg: Color,
    pub mode_normal: Color,
    pub mode_insert: Color,
    pub mode_visual: Color,
    pub mode_xlc: Color,
    pub completion_bg: Color,
    pub completion_selected: Color,
    pub completion_border: Color,
    pub explorer_bg: Color,
    pub explorer_fg: Color,
    pub explorer_dir: Color,
    pub explorer_selected: Color,
    pub terminal_bg: Color,
    #[allow(dead_code)]
    pub terminal_fg: Color,
    #[allow(dead_code)]
    pub terminal_prompt: Color,
    pub xlc_bg: Color,
    pub xlc_fg: Color,
    pub xlc_prompt: Color,
    pub xlc_border: Color,
    pub cursor: Color,
    // ── Semantic UI (feature surfaces) ──
    /// Primary interactive accent (chips, focus borders, links).
    pub accent: Color,
    /// Text drawn on `accent` background.
    pub accent_fg: Color,
    /// Secondary / dim text (hints, meta).
    pub muted: Color,
    /// Positive / staged / success.
    pub success: Color,
    /// Warning / modified.
    pub warning: Color,
    /// Error / deleted / danger.
    pub error: Color,
    /// Popup / context-menu / palette body.
    pub panel_bg: Color,
    pub panel_border: Color,
    /// Selected row inside panels/lists.
    pub panel_sel_bg: Color,
    pub panel_sel_fg: Color,
    /// Status-bar mode chips for non-vim modes.
    pub mode_git: Color,
    pub mode_term: Color,
    pub mode_preview: Color,
    pub mode_settings: Color,
    pub mode_search: Color,
    pub mode_find: Color,
    /// Diff line backgrounds + hunk header.
    pub git_add_bg: Color,
    pub git_del_bg: Color,
    pub git_hunk: Color,
}

